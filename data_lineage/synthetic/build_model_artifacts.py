"""Build the Arrows JSON and the ingest Cypher from lsc_data_model.json with the data-modeling MCP's own code.

Run with the MCP package on the path, not the project venv:

    uvx --from mcp-neo4j-data-modeling==0.8.2 python synthetic/build_model_artifacts.py

Writes lsc_data_model.arrows.json and ingest.cypher next to this file. The queries are the
MCP's get_*_cypher_ingest_query output with the patches in `_patch_*` applied.
"""

import json
import re
from pathlib import Path

from mcp_neo4j_data_modeling.data_model import DataModel

HERE = Path(__file__).resolve().parent
MODEL_PATH = HERE / "lsc_data_model.json"
ARROWS_PATH = HERE / "lsc_data_model.arrows.json"
INGEST_PATH = HERE / "ingest.cypher"


def _patch_batch_param(query: str) -> str:
    """Neo4jLoader.write_batches binds the batch as $rows."""
    return query.replace("UNWIND $records as record", "UNWIND $rows AS record")


def _patch_relationship_properties(query: str) -> str:
    """MCP 0.8.2 writes relationship properties onto the end node (`SET end += ...`)."""
    query = re.sub(r"MERGE \(start\)-\[:(\w+)\]->\(end\)", r"MERGE (start)-[r:\1]->(end)", query)
    return query.replace("SET end += {", "SET r += {")


def _patch_datetimes(query: str, datetime_props: set[str]) -> str:
    for prop in datetime_props:
        query = query.replace(f"{prop}: record.{prop}", f"{prop}: datetime(record.{prop})")
    return query


def _patch_composite_key(query: str, label: str, key: list[str]) -> str:
    """The MCP models one key property; RoleAssignment is identified by (type, scope)."""
    first, second = key
    query = query.replace(
        f"MERGE (n: {label} {{{second}: record.{second}}})",
        f"MERGE (n: {label} {{{first}: record.{first}, {second}: record.{second}}})",
    )
    query = query.replace(
        f"MATCH (start: {label} {{{second}: record.sourceId}})",
        f"MATCH (start: {label} {{{first}: record.sourceType, {second}: record.sourceId}})",
    )
    return query.replace(
        f"MATCH (end: {label} {{{second}: record.targetId}})",
        f"MATCH (end: {label} {{{first}: record.targetType, {second}: record.targetId}})",
    )


def build(model: DataModel) -> str:
    datetime_props = {
        p.name for item in [*model.nodes, *model.relationships] for p in item.properties if p.type == "DATETIME"
    }
    composite = {n.label: n.metadata["compositeKey"] for n in model.nodes if "compositeKey" in n.metadata}

    def finish(query: str) -> str:
        query = _patch_datetimes(_patch_relationship_properties(_patch_batch_param(query)), datetime_props)
        for label, key in composite.items():
            query = _patch_composite_key(query, label, key)
        return query

    steps = []
    for node in model.nodes:
        if node.label in composite:
            fields = ", ".join(f"n.{k}" for k in composite[node.label])
            constraint = f"CREATE CONSTRAINT {node.label}_constraint IF NOT EXISTS FOR (n:{node.label}) REQUIRE ({fields}) IS NODE KEY"
        else:
            constraint = node.get_cypher_constraint_query()
        if node.metadata.get("keyConstraint") == "UNIQUE":
            constraint = constraint.replace("IS NODE KEY", "IS UNIQUE")
        steps.append((f"constraint {node.label}", constraint))
    for node in model.nodes:
        steps.append((f"node {node.label}", finish(model.get_node_cypher_ingest_query_for_many_records(node.label))))
    for node in model.nodes:
        key = node.key_property.name
        for extra in node.metadata.get("extraLabels", []):
            steps.append((
                f"label {node.label} {extra}",
                f"UNWIND $rows AS record\nMATCH (n: {node.label} {{{key}: record.{key}}})\nSET n:{extra}",
            ))
    for rel in model.relationships:
        query = model.get_relationship_cypher_ingest_query_for_many_records(
            rel.type, rel.start_node_label, rel.end_node_label
        )
        steps.append((f"rel {rel.start_node_label}-{rel.type}-{rel.end_node_label}", finish(query)))

    header = (
        "// Generated by synthetic/build_model_artifacts.py from lsc_data_model.json. Do not edit by hand.\n"
        "// Each step binds one data file as $rows: node X -> nodes/X.jsonl, label X Y -> labels/X-Y.jsonl,\n"
        "// rel A-T-B -> rels/A-T-B.jsonl. Constraints run once, first.\n\n"
    )
    return header + "\n\n".join(f"// step: {name}\n{query};" for name, query in steps) + "\n"


def main() -> None:
    raw = json.loads(MODEL_PATH.read_text(encoding="utf-8"))
    model = DataModel.model_validate(raw)
    arrows = model.to_arrows_dict()
    for node in arrows["nodes"]:
        extra = next((n.get("metadata", {}).get("extraLabels") for n in raw["nodes"] if n["label"] == node["id"]), None)
        node["caption"] = f"+ :{' | :'.join(extra)}" if extra else ""
    ARROWS_PATH.write_text(json.dumps(arrows, indent=2) + "\n", encoding="utf-8")
    INGEST_PATH.write_text(build(model), encoding="utf-8")
    print(f"{len(model.nodes)} nodes, {len(model.relationships)} relationships -> {ARROWS_PATH.name}, {INGEST_PATH.name}")


if __name__ == "__main__":
    main()
