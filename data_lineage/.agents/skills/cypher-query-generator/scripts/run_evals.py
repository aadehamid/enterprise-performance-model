"""
Batch Eval Runner for Output Quality Evaluation.

Reads evals.json, generates Cypher queries for each test case (from provided
query files or by prompting the user), validates them against Neo4j, captures
timing data, and aggregates results into benchmark.json.

Usage:
    # Run WITH skill (default):
    python run_evals.py --evals evals/evals.json --iteration 1 --interactive

    # Run WITHOUT skill (baseline):
    python run_evals.py --evals evals/evals.json --iteration 1 --interactive --mode without_skill

    # Run from pre-written query files:
    python run_evals.py --evals evals/evals.json --iteration 2 --queries-dir iteration-2-queries/

    # Run a single eval by ID:
    python run_evals.py --evals evals/evals.json --iteration 2 --interactive --eval-id 3

Dependencies: neo4j, python-dotenv
"""

import argparse
import json
import os
import sys
import time
from datetime import datetime

# Add scripts dir to path for validate_cypher import
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, SCRIPT_DIR)

from validate_cypher import connect, validate_query


def slugify(text, max_len=50):
    """Convert text to a filesystem-safe slug."""
    slug = text.lower()
    slug = "".join(c if c.isalnum() or c in (" ", "-") else "" for c in slug)
    slug = "-".join(slug.split())
    return slug[:max_len]


def safe_print(text):
    """Safely print text to the Windows console, replacing problematic characters."""
    sanitized = text.replace('→', '->').replace('—', '-')
    print(sanitized)


def run_evals(evals_file, iteration, workspace_dir, queries_dir=None,
              interactive=False, eval_id=None, env_path=None, mode="with_skill"):
    """Run output quality evals and generate grading + timing + benchmark."""
    with open(evals_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    evals = data["evals"]
    if eval_id is not None:
        evals = [e for e in evals if e["id"] == eval_id]
        if not evals:
            print(f"ERROR: No eval found with id={eval_id}")
            sys.exit(1)

    iter_dir = os.path.join(workspace_dir, f"iteration-{iteration}")
    os.makedirs(iter_dir, exist_ok=True)

    # Connect to Neo4j
    from validate_cypher import DEFAULT_ENV_PATH
    env = env_path or DEFAULT_ENV_PATH
    driver, database = connect(env)

    eval_results = []

    try:
        for ev in evals:
            eid = ev["id"]
            prompt = ev["prompt"]
            slug = f"eval-{eid}-{slugify(prompt, 40)}"

            safe_print(f"\n{'='*60}")
            safe_print(f"  Eval {eid}: {prompt[:70]}")
            safe_print(f"{'='*60}")

            # Get the Cypher query
            cypher_query = None

            if queries_dir:
                # Look for pre-written query file
                query_file = os.path.join(queries_dir, f"eval-{eid}.cypher")
                if os.path.exists(query_file):
                    with open(query_file, "r", encoding="utf-8") as f:
                        cypher_query = f.read().strip()
                    print(f"  Loaded query from: {query_file}")
                else:
                    print(f"  WARNING: No query file found at {query_file}")

            if cypher_query is None and interactive:
                safe_print(f"\n  Prompt: \"{prompt}\"")
                safe_print(f"  Expected: {ev.get('expected_output', 'N/A')}")
                safe_print(f"\n  Paste the Cypher query generated by the agent below.")
                safe_print(f"  End with an empty line:")
                lines = []
                while True:
                    line = input()
                    if line.strip() == "":
                        break
                    lines.append(line)
                cypher_query = "\n".join(lines)

            if not cypher_query:
                print(f"  SKIPPED — no query available")
                continue

            # Create output directory
            out_dir = os.path.join(iter_dir, slug, mode)
            os.makedirs(os.path.join(out_dir, "outputs"), exist_ok=True)

            # Save the query
            with open(os.path.join(out_dir, "outputs", "query.cypher"), "w", encoding="utf-8") as f:
                f.write(cypher_query)

            # Run validation with timing
            start_time = time.time()
            grading = validate_query(driver, database, cypher_query)
            duration_ms = round((time.time() - start_time) * 1000)

            # Write grading.json
            with open(os.path.join(out_dir, "grading.json"), "w", encoding="utf-8") as f:
                json.dump(grading, f, indent=2)

            # Write timing.json
            timing = {
                "duration_ms": duration_ms,
                "timestamp": datetime.now().isoformat()
            }
            with open(os.path.join(out_dir, "timing.json"), "w", encoding="utf-8") as f:
                json.dump(timing, f, indent=2)

            # Write empty feedback.json placeholder
            feedback_file = os.path.join(iter_dir, slug, "feedback.json")
            if not os.path.exists(feedback_file):
                with open(feedback_file, "w", encoding="utf-8") as f:
                    json.dump({
                        "eval_id": eid,
                        "human_feedback": "",
                        "reviewed": False
                    }, f, indent=2)

            # Print result
            passed = grading["summary"]["passed"]
            total = grading["summary"]["total"]
            rate = grading["summary"]["pass_rate"]
            safe_print(f"  Result: {passed}/{total} assertions passed ({rate:.0%}) [{duration_ms}ms]")

            eval_results.append({
                "id": slug,
                "eval_id": eid,
                "pass_rate": rate,
                "passed": passed,
                "total": total,
                "duration_ms": duration_ms
            })

    finally:
        driver.close()

    # Aggregate benchmark
    if eval_results:
        pass_rates = [r["pass_rate"] for r in eval_results]
        durations = [r["duration_ms"] for r in eval_results]
        mean_pr = round(sum(pass_rates) / len(pass_rates), 2)
        mean_dur = round(sum(durations) / len(durations))

        # Compute stddev
        import math
        if len(pass_rates) > 1:
            pr_std = round(math.sqrt(sum((x - mean_pr)**2 for x in pass_rates) / (len(pass_rates) - 1)), 3)
            dur_std = round(math.sqrt(sum((x - mean_dur)**2 for x in durations) / (len(durations) - 1)))
        else:
            pr_std = 0
            dur_std = 0

        current_mode_data = {
            "pass_rate": {"mean": mean_pr, "stddev": pr_std},
            "time_ms": {"mean": mean_dur, "stddev": dur_std},
            "eval_results": eval_results
        }

        # Load existing benchmark if it exists (to merge with_skill + without_skill)
        benchmark_file = os.path.join(iter_dir, "benchmark.json")
        if os.path.exists(benchmark_file):
            with open(benchmark_file, "r", encoding="utf-8") as f:
                benchmark = json.load(f)
        else:
            benchmark = {
                "run_summary": {
                    "with_skill": {"pass_rate": {"mean": None}, "time_ms": {"mean": None}, "eval_results": []},
                    "without_skill": {"pass_rate": {"mean": None}, "time_ms": {"mean": None}, "eval_results": []},
                    "delta": {"pass_rate": None, "time_ms": None}
                },
                "timestamp": datetime.now().isoformat(),
                "iteration": iteration
            }

        # Update the current mode
        benchmark["run_summary"][mode] = current_mode_data
        benchmark["timestamp"] = datetime.now().isoformat()

        # Auto-compute delta if both modes have data
        ws = benchmark["run_summary"]["with_skill"]
        wos = benchmark["run_summary"]["without_skill"]
        if (ws.get("pass_rate", {}).get("mean") is not None and
                wos.get("pass_rate", {}).get("mean") is not None):
            benchmark["run_summary"]["delta"] = {
                "pass_rate": round(ws["pass_rate"]["mean"] - wos["pass_rate"]["mean"], 2),
                "time_ms": round(ws["time_ms"]["mean"] - wos["time_ms"]["mean"]) if ws["time_ms"]["mean"] and wos["time_ms"]["mean"] else None
            }

        with open(benchmark_file, "w", encoding="utf-8") as f:
            json.dump(benchmark, f, indent=2)

        safe_print(f"\n{'='*60}")
        safe_print(f"  BENCHMARK - Iteration {iteration} ({mode})")
        safe_print(f"{'='*60}")
        safe_print(f"  Pass rate: {mean_pr:.0%} (stddev: {pr_std:.3f})")
        safe_print(f"  Avg time:  {mean_dur}ms (stddev: {dur_std}ms)")
        safe_print(f"  Results:   {len(eval_results)} evals")
        if benchmark["run_summary"]["delta"].get("pass_rate") is not None:
            delta_pr = benchmark["run_summary"]["delta"]["pass_rate"]
            safe_print(f"  Delta:     {'+' if delta_pr > 0 else ''}{delta_pr:.0%} pass rate vs. baseline")
        safe_print(f"  Output:    {benchmark_file}")
        safe_print("")


def main():
    parser = argparse.ArgumentParser(
        description="Batch eval runner for skill output quality evaluation"
    )
    parser.add_argument("--evals", "-e", required=True,
                        help="Path to evals.json")
    parser.add_argument("--iteration", "-i", type=int, required=True,
                        help="Iteration number (creates iteration-N/ directory)")
    parser.add_argument("--queries-dir", "-q",
                        help="Directory containing pre-written eval-N.cypher files")
    parser.add_argument("--interactive", action="store_true",
                        help="Interactively paste Cypher queries for each prompt")
    parser.add_argument("--eval-id", type=int,
                        help="Run only a specific eval by ID")
    parser.add_argument("--workspace", "-w",
                        default=os.path.join(os.path.dirname(SCRIPT_DIR),
                                             "..", "cypher-query-generator-workspace"),
                        help="Path to workspace directory")
    parser.add_argument("--env",
                        help="Path to Neo4j credentials .env file")
    parser.add_argument("--mode", "-m", choices=["with_skill", "without_skill"],
                        default="with_skill",
                        help="Output mode: with_skill (default) or without_skill (baseline)")
    args = parser.parse_args()

    if not args.queries_dir and not args.interactive:
        print("ERROR: Must specify either --queries-dir or --interactive")
        sys.exit(1)

    run_evals(
        evals_file=args.evals,
        iteration=args.iteration,
        workspace_dir=os.path.abspath(args.workspace),
        queries_dir=args.queries_dir,
        interactive=args.interactive,
        eval_id=args.eval_id,
        env_path=args.env,
        mode=args.mode
    )


if __name__ == "__main__":
    main()
