import { useEffect, useRef, useState } from 'react';
import { v4 as uuidv4 } from 'uuid';
import {
  isAbort,
  postAsk,
  postFeedback,
  type AskResponse,
  type AskSource,
  type Feedback,
  type GraphPayload,
} from '../api/backend';

export const MODEL_LABEL = 'Azure OpenAI (gpt-5.4)';

export type ChatMessage = {
  id: number;
  user: 'user' | 'chatbot';
  message: string;
  datetime: string;
  isTyping?: boolean;
  isGreeting?: boolean;
  entities?: AskSource[];
  model?: string;
  timeTaken?: number;
};

export type AskResult = {
  id: number;
  cypher: string;
  error: string;
  graphData: GraphPayload | null;
  rows: Record<string, any>[];
  model: string;
  timeTaken: number;
  headers: Record<string, string>;
};

type Reply = Pick<ChatMessage, 'entities' | 'model' | 'timeTaken'> & { reply: string };

const GREETING = `Hello! I'm your Enterprise Semantic Portal Chatbot built on the Lagos Refining & Supply Company Knowledge Graph.
      \n Ask me any questions in English about table flow, column lineages, report dependencies, legacy refactorings, or master data mappings, and I'll fetch the results for you in text, graph, and tabular views!
      \n How can I help you today?`;

const COMPLEX_QUESTION =
  /path|lineage|derived|flow|consum|report|legacy|server|datasystem|system|concept|domain|product|flatfile/i;

const now = () => {
  const date = new Date();
  return `${date.toLocaleDateString()} ${date.toLocaleTimeString()}`;
};

function toResult(response: AskResponse, startTime: number): { result: AskResult; reply: Reply } {
  const first = response.src?.[0];
  const timeTaken = Date.now() - startTime;
  return {
    result: {
      id: startTime,
      cypher: response.cypher ?? '',
      error: response.error ?? '',
      graphData: first?.graph_data ?? null,
      rows: first?.rows ?? [],
      model: MODEL_LABEL,
      timeTaken,
      headers: first?.headers ?? {},
    },
    reply: {
      reply: response.response || 'Query executed successfully, but no narrative response was generated by the model.',
      entities: response.src,
      model: MODEL_LABEL,
      timeTaken,
    },
  };
}

const typingChunk = (length: number) => (length > 800 ? 8 : length > 400 ? 5 : length > 150 ? 3 : 2);

export function useAsk() {
  const [messages, setMessages] = useState<ChatMessage[]>(() => [
    { id: 1, user: 'chatbot', message: GREETING, datetime: '01/01/2024 00:00:00', isGreeting: true },
  ]);
  const [result, setResult] = useState<AskResult | null>(null);
  const [pending, setPending] = useState<{ validating: boolean } | null>(null);
  const [sessionId] = useState(() => uuidv4());

  const abortRef = useRef<AbortController | null>(null);
  const typingTimeoutRef = useRef<ReturnType<typeof setTimeout> | null>(null);
  const typingReplyRef = useRef<Reply | null>(null);

  const typeReply = (reply: Reply, index = 0) => {
    const text = reply.reply;
    if (index === 0) {
      if (typingTimeoutRef.current) clearTimeout(typingTimeoutRef.current);
      typingReplyRef.current = reply;
    }

    if (index >= text.length) {
      setMessages((msgs) => msgs.map((msg) => (msg.isTyping ? { ...msg, isTyping: false } : msg)));
      typingTimeoutRef.current = null;
      return;
    }

    const nextIndex = Math.min(index + typingChunk(text.length), text.length);
    const typed = text.substring(0, nextIndex);
    if (index > 0) {
      setMessages((msgs) => msgs.map((msg) => (msg.isTyping ? { ...msg, message: typed } : msg)));
    } else {
      const { entities, model, timeTaken } = reply;
      const bubble = {
        id: Date.now(),
        user: 'chatbot' as const,
        message: typed,
        datetime: now(),
        isTyping: true,
        entities,
        model,
        timeTaken,
      };
      setMessages((msgs) =>
        text.length <= 1
          ? [...msgs, bubble]
          : msgs.map((msg, idx) => (idx === msgs.length - 1 ? { ...msg, ...bubble } : msg)),
      );
    }
    typingTimeoutRef.current = setTimeout(() => typeReply(reply, nextIndex), 3);
  };

  useEffect(() => {
    typeReply({ reply: GREETING });
    return () => {
      if (typingTimeoutRef.current) clearTimeout(typingTimeoutRef.current);
      abortRef.current?.abort();
    };
  }, []);

  const ask = async (question: string) => {
    setMessages((msgs) => [...msgs, { id: Date.now(), user: 'user', message: question, datetime: now() }]);
    setPending({ validating: COMPLEX_QUESTION.test(question) });
    typeReply({ reply: ' ' });

    abortRef.current = new AbortController();
    try {
      const startTime = Date.now();
      const response = await postAsk(question, sessionId, abortRef.current.signal);
      const { result, reply } = toResult(response, startTime);
      setResult(result);
      typeReply(reply);
    } catch (error: any) {
      if (isAbort(error)) return;
      console.error('Error in chat response processing:', error);
      const errMsg =
        error?.response?.data?.detail || error?.message || 'Failed to communicate with the FastAPI backend gateway.';
      typeReply({
        reply: `⚠️ Connection Error: ${errMsg}\n\nPlease verify that your FastAPI backend server is started and successfully listening on http://localhost:8000.`,
      });
    } finally {
      setPending(null);
      abortRef.current = null;
    }
  };

  const stop = () => {
    if (pending) {
      abortRef.current?.abort();
      setPending(null);
      setMessages((msgs) => {
        const last = msgs[msgs.length - 1];
        return last?.user === 'chatbot' && last.message === ' ' ? msgs.slice(0, -1) : msgs;
      });
    }

    if (messages.some((msg) => msg.isTyping)) {
      if (typingTimeoutRef.current) {
        clearTimeout(typingTimeoutRef.current);
        typingTimeoutRef.current = null;
      }
      const reply = typingReplyRef.current;
      if (reply) {
        setMessages((msgs) =>
          msgs.map((msg) =>
            msg.isTyping
              ? {
                  ...msg,
                  message: reply.reply,
                  isTyping: false,
                  entities: reply.entities,
                  model: reply.model,
                  timeTaken: reply.timeTaken,
                }
              : msg,
          ),
        );
      }
    }
  };

  const sendFeedback = async (feedback: Feedback, comment: string) => {
    try {
      await postFeedback(sessionId, feedback, comment);
    } catch (error) {
      console.error('Secure feedback submission failed:', error);
    }
  };

  const isAsking = pending !== null;
  const isBusy = isAsking || messages.some((msg) => msg.isTyping);

  return { messages, result, isAsking, isValidating: pending?.validating ?? false, isBusy, ask, stop, sendFeedback };
}
